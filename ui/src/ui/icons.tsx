/** A QR-like square for the pairing page. A real code comes from the backend later. */
export function QrSquare({ seed }: { seed: string }) {
  const n = 21, cells: string[] = [];
  let h = 0;
  for (const c of seed) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  const finder = (x: number, y: number, a: number, b: number) => {
    const dx = x - a, dy = y - b;
    return dx === 0 || dx === 6 || dy === 0 || dy === 6 || (dx > 1 && dx < 5 && dy > 1 && dy < 5);
  };
  for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
    let on: boolean;
    if (x < 7 && y < 7) on = finder(x, y, 0, 0);
    else if (x >= 14 && y < 7) on = finder(x, y, 14, 0);
    else if (x < 7 && y >= 14) on = finder(x, y, 0, 14);
    else if (x < 8 && y < 8 || x > 12 && y < 8 || x < 8 && y > 12) on = false;
    else on = ((x * 7 + y * 13 + x * y * 3 + h) % 5) < 2;
    if (on) cells.push(`M${x} ${y}h1.02v1.02h-1.02z`);
  }
  return <svg class="qr" viewBox="-1 -1 23 23" role="img" aria-label="Pairing code"><path d={cells.join('')} fill="currentColor" /></svg>;
}
